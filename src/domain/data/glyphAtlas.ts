/**
 * Glyph atlas for the archive's 520x400 renderer — see `domain/archiveImport.ts`.
 *
 * One of three: each render size has its own font and so its own table
 * (`glyphAtlas10x12.ts`, `glyphAtlas8x10.ts`).
 *
 * The archive renderer draws text with a fixed bitmap font and no
 * anti-aliasing, so every occurrence of a character is the *identical* 13x16
 * pixel stencil. That makes import a lookup rather than a recognition problem:
 * this file maps each stencil to the character it draws.
 *
 * ## Key format
 *
 * 16 rows of 4 hex digits, one group per pixel row, most-significant bit =
 * leftmost pixel (x=0 is bit 12; the top 3 bits of each group are always 0
 * because a cell is 13 pixels wide). See `glyphKey` in `domain/archiveImport.ts`
 * — that function is the only place keys are produced, and this table the only
 * place they are consumed.
 *
 * ## Where these came from
 *
 * Read off the RTP Teletexto corpus — every stencil the renderer produced
 * across 631 archived pages, identified from the words it appears in and
 * checked against the character-set chart the archive itself published on page
 * 106, which lays the whole set out by code point. As of that pass the decoder
 * reads all 631 pages with nothing left unrecognised.
 *
 * Double height needs no entries of its own. The renderer draws a tall line by
 * doubling every source row across two cells; `domain/archiveImport.ts`
 * reconstructs the original 16-row stencil and looks it up here, so a character
 * learnt at one height is known at both. (A stencil recovered that way can
 * differ from its single-height twin by a pixel, which is why a few characters
 * appear under more than one key.)
 *
 * ## Growing the table
 *
 * Coverage is complete for this renderer: all 631 of its pages in the corpus
 * decode with nothing unrecognised. If some later page does turn up an unknown
 * stencil, the `/import` screen lists it and lets you name it; "Copy for
 * glyphAtlas.ts" there emits lines in exactly this format to paste in below.
 * Entries are sorted by character.
 */

